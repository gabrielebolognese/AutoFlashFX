#!/usr/bin/env python
"""pass-schemas.py: write the three pass schemas (09a-animations, 09b-text, 09c-transitions: schema.json) from the merged
plan schema in this folder, so the parts stay one definition. Run after editing schema.json:
    python pipeline/stages/09-plan/pass-schemas.py [OUT_DIR]
"""
import copy
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
STAGES = os.path.dirname(HERE)


def load(path):
    with open(path, encoding="utf-8-sig") as f:
        return json.load(f)


def dump(path, data):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")


def main():
    out_root = STAGES
    if len(sys.argv) > 1:  # an output folder with 09a-animations/, 09b-text/, 09c-transitions/ subfolders (the test compares)
        out_root = sys.argv[1]
        for d in ("09a-animations", "09b-text", "09c-transitions"):
            os.makedirs(os.path.join(out_root, d), exist_ok=True)
    merged = load(os.path.join(HERE, "schema.json"))
    props = merged["properties"]
    base = {"$schema": merged["$schema"]}
    # 9a: the scenes, the branding, the solution, hook 2, the wishlist
    a = copy.deepcopy(base)
    a["$id"] = "https://instagramreels.local/stages/09a-animations/plan.json"
    a["title"] = "09a-animations plan.json: the animations pass of the visual plan (BUILD_SPEC.md S9 9a; generated from 09-plan/schema.json by pass-schemas.py)"
    a["type"] = "object"
    a["required"] = ["pass", "plan_version", "fps", "duration_ms", "scenes", "branding"]
    a["properties"] = {"pass": {"const": "animations"}}
    for k in ("plan_version", "style", "idea_id", "source", "fps", "duration_ms", "voice", "solution", "tracker", "branding", "scenes", "hook2", "wishlist", "notes"):
        a["properties"][k] = copy.deepcopy(props[k])
    dump(os.path.join(out_root, "09a-animations", "schema.json"), a)
    # 9b: the captions, the card texts the pass changed (overrides), the derived cards and labels
    b = copy.deepcopy(base)
    b["$id"] = "https://instagramreels.local/stages/09b-text/plan.json"
    b["title"] = "09b-text plan.json: the text pass of the visual plan (BUILD_SPEC.md S9 9b; generated by pass-schemas.py)"
    b["type"] = "object"
    b["required"] = ["pass", "captions", "cards", "labels"]
    b["properties"] = {"pass": {"const": "text"},
                       "captions": copy.deepcopy(props["captions"]),
                       "overrides": {"type": "array", "description": "the card texts the pass changed: applied to the 9a instances' props by the merge",
                                     "items": {"type": "object", "required": ["component", "prop", "text"],
                                               "properties": {"scene": {"type": "string"}, "component": {"type": "string"}, "prop": {"type": "string"}, "text": {"type": "string"}}}},
                       "cards": copy.deepcopy(props["cards"]), "labels": copy.deepcopy(props["labels"]), "notes": {"type": "string"}}
    dump(os.path.join(out_root, "09b-text", "schema.json"), b)
    # 9c: the transitions
    c = copy.deepcopy(base)
    c["$id"] = "https://instagramreels.local/stages/09c-transitions/plan.json"
    c["title"] = "09c-transitions plan.json: the transitions pass of the visual plan (BUILD_SPEC.md S9 9c; generated by pass-schemas.py); merged.json beside it is the whole plan"
    c["type"] = "object"
    c["required"] = ["pass", "transitions"]
    c["properties"] = {"pass": {"const": "transitions"}, "transitions": copy.deepcopy(props["transitions"]), "notes": {"type": "string"}}
    c["properties"]["transitions"]["items"]["required"] = ["from", "to", "type", "duration_ms"]
    dump(os.path.join(out_root, "09c-transitions", "schema.json"), c)
    print("pass schemas written: 09a-animations, 09b-text, 09c-transitions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
